from __future__ import annotations
from pathlib import Path
from typing import List
from ..models import SearchResult, RunSummary

def export_markdown(results: List[SearchResult], summary: RunSummary, output_path: Path) -> Path:
    """Generate an executive Markdown intelligence report."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# DorkForge Reconnaissance Report: {summary.target_domain}",
        "",
        f"**Generated At:** `{summary.timestamp}`  ",
        f"**Target Domain:** `{summary.target_domain}`  ",
        f"**Total Queries Executed:** `{summary.executed_queries}` / `{summary.total_queries}`  ",
        f"**Total Findings Discovered:** `{summary.total_results}` (Unique: `{summary.unique_results}`)  ",
        f"**Execution Dwell Time:** `{summary.execution_time_seconds:.2f}s`  ",
        "",
        "## Category Distribution",
        "",
        "| Category | Findings Count |",
        "| :--- | :--- |"
    ]

    for cat, count in sorted(summary.results_by_category.items(), key=lambda x: x[1], reverse=True):
        lines.append(f"| **{cat}** | `{count}` |")

    lines.extend([
        "",
        "## Search Engine Telemetry",
        "",
        "| Engine | Results Count |",
        "| :--- | :--- |"
    ])

    for eng, count in sorted(summary.results_by_engine.items(), key=lambda x: x[1], reverse=True):
        lines.append(f"| `{eng}` | `{count}` |")

    lines.extend([
        "",
        "## Detailed Findings",
        ""
    ])

    # Group results by category
    cats = {}
    for r in results:
        cats.setdefault(r.category, []).append(r)

    for cat, items in sorted(cats.items()):
        lines.append(f"### {cat} ({len(items)})")
        lines.append("")
        for idx, item in enumerate(items, 1):
            lines.append(f"#### {idx}. [{item.title}]({item.url})")
            lines.append(f"- **URL:** `{item.url}`")
            lines.append(f"- **Engine:** `{item.engine}` | **Confidence:** `{int(item.confidence * 100)}%`")
            lines.append(f"- **Dork Query:** `{item.query}`")
            if item.snippet:
                lines.append(f"- **Snippet:** *{item.snippet}*")
            lines.append("")

    lines.extend([
        "---",
        "*Report generated by DorkForge Automated OSINT Reconnaissance Framework.*"
    ])

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return output_path
